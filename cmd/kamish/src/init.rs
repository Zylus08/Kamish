use ed25519_dalek::SigningKey;
use kamish_policy::{
    AckMode, ClassRule, DestinationMode, PolicyDocument, SignedPolicy,
};
use rand::rngs::OsRng;
use std::collections::{HashMap, HashSet};
use std::fs;
use std::path::Path;

pub async fn run_init(force: bool) -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
    println!("\x1b[1;35m==============================================================================\x1b[0m");
    println!("\x1b[1;36m  KAMISH CLUSTER INITIALIZATION (ADR-006)                                     \x1b[0m");
    println!("\x1b[1;35m==============================================================================\x1b[0m\n");

    let config_path = Path::new("kamish.toml");
    if config_path.exists() && !force {
        println!("\x1b[1;33m[kamish init] Configuration file 'kamish.toml' already exists.\x1b[0m");
        println!("Use --force to overwrite existing configuration and keys.\n");
        return Ok(());
    }

    // 1. Create data directories
    fs::create_dir_all("data/broker")?;
    fs::create_dir_all("data/gateway-broker")?;
    println!("\x1b[1;32m[✓]\x1b[0m Created data directories (./data/broker, ./data/gateway-broker)");

    // 2. Generate Ed25519 Signing Keys
    let signing_key = SigningKey::generate(&mut OsRng);
    let verifying_key = signing_key.verifying_key();
    let pubkey_hex = hex::encode(verifying_key.to_bytes());
    let privkey_hex = hex::encode(signing_key.to_bytes());

    fs::write("policy.pub", &pubkey_hex)?;
    fs::write("policy.key", &privkey_hex)?;
    println!("\x1b[1;32m[✓]\x1b[0m Generated Ed25519 Policy Signing Keypair:");
    println!("    Public Key Hex : {}", pubkey_hex);
    println!("    Saved to       : policy.pub & policy.key");

    // 3. Author and Sign Genesis Residency Policy
    let mut legal_regions = HashSet::new();
    legal_regions.insert("EU_WEST".to_string());
    legal_regions.insert("US_EAST".to_string());
    legal_regions.insert("AP_SOUTH".to_string());

    let mut sovereign_modes = HashMap::new();
    sovereign_modes.insert("EU_WEST".to_string(), DestinationMode::Cleartext);

    let mut general_modes = HashMap::new();
    general_modes.insert("EU_WEST".to_string(), DestinationMode::Cleartext);
    general_modes.insert("US_EAST".to_string(), DestinationMode::Cleartext);
    general_modes.insert("AP_SOUTH".to_string(), DestinationMode::Cleartext);

    let mut classes = HashMap::new();
    classes.insert(
        "sovereign-class".to_string(),
        ClassRule {
            class_id: "sovereign-class".to_string(),
            description: "Strict Sovereign In-Region Data Class".to_string(),
            legal_regions: {
                let mut s = HashSet::new();
                s.insert("EU_WEST".to_string());
                s
            },
            destination_modes: sovereign_modes,
            ack_mode: AckMode::LocalMajority,
            failover_candidates: vec!["EU_WEST".to_string()],
            transit_allowed: false,
        },
    );
    classes.insert(
        "general".to_string(),
        ClassRule {
            class_id: "general".to_string(),
            description: "General Multi-Region Replicated Topic".to_string(),
            legal_regions,
            destination_modes: general_modes,
            ack_mode: AckMode::LocalMajority,
            failover_candidates: vec!["US_EAST".to_string(), "AP_SOUTH".to_string()],
            transit_allowed: true,
        },
    );

    let doc = PolicyDocument {
        policy_id: "pol-genesis".to_string(),
        version: 1,
        issued_at_sec: chrono::Utc::now().timestamp(),
        ttl_seconds: 86400 * 365, // 1 year validity
        issuer_pubkey_hex: pubkey_hex.clone(),
        classes,
        transit_rules: HashMap::new(),
    };

    let signed_policy = SignedPolicy::sign(doc, &signing_key);
    let signed_json = serde_json::to_string_pretty(&signed_policy)?;
    fs::write("policy.json", signed_json)?;
    println!("\x1b[1;32m[✓]\x1b[0m Authored and cryptographically signed genesis policy document (policy.json)");

    // 4. Author kamish.toml
    let toml_content = format!(
        r#"# Kamish Cluster Configuration (ADR-006)
# Generated by `kamish init`

[cluster]
cluster_id = "kamish-local-cluster"
environment = "development"

[broker]
region = "EU_WEST"
host = "127.0.0.1"
port = 8080
data_dir = "./data/broker"
peers = ["US_EAST", "AP_SOUTH"]
ack_level = "LeaderFsync"

[gateway]
host = "127.0.0.1"
port = 3001
data_dir = "./data/gateway-broker"
dev = true
insecure_dev = false

[policy]
policy_file = "policy.json"
trusted_keys = ["{}"]
default_class = "general"
strict_local_shield = true
"#,
        pubkey_hex
    );

    fs::write("kamish.toml", toml_content)?;
    println!("\x1b[1;32m[✓]\x1b[0m Wrote cluster configuration skeleton to 'kamish.toml'");

    println!("\n\x1b[1;32mInitialization complete!\x1b[0m");
    println!("Next steps:");
    println!("  1. Run '\x1b[1mkamish doctor\x1b[0m' to verify ports and system prerequisites.");
    println!("  2. Run '\x1b[1mkamish start --dev\x1b[0m' (or '\x1b[1mkamish run --dev\x1b[0m') to launch the unified broker, gateway, and dashboard.\n");

    Ok(())
}
